const homes = specs.map(
  ([
    seedKey,
    title,
    address,
    city,
    state,
    type,
    bedrooms,
    bathrooms,
    squareFeet,
    rent,
    photo,
    description,
  ]) => ({
    seedKey,
    title,
    address,
    city,
    state,
    type,
    bedrooms,
    bathrooms,
    squareFeet,
    rent,
    description,
    imageUrl: `/images/homes/${photo}.jpg`,
    isDemo: true,
  }),
);

async function seedHomes(branchId) {
  const { Property } = require("../models");
  let added = 0,
    illustrated = 0;
  for (const [index, home] of homes.entries()) {
    let existing = await Property.findOne({ seedKey: home.seedKey });
    // Adopt the three exact original seed records, preserving their terms/status.
    if (!existing && index < 3)
      existing = await Property.findOne({
        title: home.title,
        address: home.address,
        city: home.city,
        description: home.description,
      });
    if (existing) {
      const changes = { seedKey: home.seedKey, isDemo: true };
      if (!existing.imageUrl) {
        changes.imageUrl = home.imageUrl;
        illustrated++;
      }
      await Property.updateOne({ _id: existing._id }, { $set: changes });
    } else {
      const result = await Property.updateOne(
        { seedKey: home.seedKey },
        { $setOnInsert: { ...home, branch: branchId, status: "available" } },
        { upsert: true },
      );
      added += result.upsertedCount;
    }
  }
  return { added, illustrated, catalogSize: homes.length };
}
module.exports = { homes, seedHomes };
